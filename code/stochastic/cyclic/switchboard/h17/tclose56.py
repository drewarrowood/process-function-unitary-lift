"""H.17.16b (Track A2): Klein-cluster family KC with k = 5 and 6 classes, LAZY job generation.
Same model, filters and solver as tclose4.py (imports tclose4.solve); the only change is that jobs are generated by a
backtracking generator over the class pairs (filter A: no single-string support; filter C: triple consistency checked as soon
as all three pairs of a triple are assigned), streamed to the worker pool and never materialised.  The old tclose4.gen_jobs
built every product in memory (OOM at k=5).  Checkpoint: tclose56_done.txt.gz, one JSON line per block (K index, class subset);
rerun the same command to resume (finished blocks are skipped).  Usage: NPROC=3 nohup python3 tclose56.py 5 >> tclose56.log 2>&1 &"""
import os, sys, json, gzip, itertools as it, time
from multiprocessing import Pool
import tclose4 as T4
from tclose3 import patterns
def lazy_jobs(cls):
    k=len(cls); prs=list(it.combinations(range(k),2))
    pl=[[tuple(S) for S in patterns(cls[i],cls[j]) if len(S)!=1] for i,j in prs]
    pl=[[frozenset(S) for S in dict.fromkeys(p)] for p in pl]
    idx={p:n for n,p in enumerate(prs)}
    # triples that become complete when pair n is assigned (n = largest index among the triple's pairs)
    tri={n:[] for n in range(len(prs))}
    for i,j,l in it.combinations(range(k),3):
        a,b,c=idx[(i,j)],idx[(i,l)],idx[(j,l)]; tri[max(a,b,c)].append((a,b,c))
    cur=[None]*len(prs)
    def ok(n):
        for a,b,c in tri[n]:
            A,B,C=cur[a],cur[b],cur[c]
            if not (B<={x^y for x in A for y in C} and A<={x^y for x in B for y in C} and C<={x^y for x in A for y in B}): return False
        return True
    def rec(n):
        if n==len(prs):
            yield {'%d,%d'%p:sorted(cur[m]) for m,p in enumerate(prs)}; return
        for S in pl[n]:
            cur[n]=S
            if ok(n): yield from rec(n+1)
        cur[n]=None
    yield from rec(0)
def work(a):
    cls,sup=a; r=T4.solve(dict(cls=cls,sup=sup))
    return (None if r is None else ('UNRESOLVED' if r=='UNRESOLVED' else r), sup)
def stab_subsets(K,k):
    """Class subsets of the cluster up to the stabiliser of K in G48 (sound by the H.17.15(d) argument: g maps the
    cluster to itself, boards to boards and patterns to patterns)."""
    from t3sym import G, act
    cl=T4.cluster(K); stab=[]
    for g in G:
        img=[tuple(sorted(act(s,*g) for s in c)) for c in cl]
        if sorted(img)==sorted(cl): stab.append([cl.index(c) for c in img])
    return sorted({min(tuple(sorted(p[i] for i in s)) for p in stab) for s in it.combinations(range(6),k)})
if __name__=='__main__':
    k=int(sys.argv[1]); NP=int(os.environ.get('NPROC','3')); CK='tclose56_done.txt.gz'; done=set()
    if os.path.exists(CK):
        for l in gzip.open(CK,'rt'): done.add(json.dumps(json.loads(l)['blk']))
    reps,nK=T4.klein_reps()
    blocks=[(ki,K,sub) for ki,K in enumerate(reps) for sub in stab_subsets(K,k)]
    blocks.sort(key=lambda b:(sum(1 for i in b[2] if i<3),b[0]))      # cheap blocks (fewer 3-term classes) first
    print('k',k,'Klein orbits',len(reps),'blocks',len(blocks),'done',len(done),flush=True)
    tot=dict(jobs=0,cand=0,unres=0); t0=time.time()
    with Pool(NP) as pool:
        for ki,K,sub in blocks:
            blk=[ki,k,list(sub)]
            if json.dumps(blk) in done: continue
            cl=T4.cluster(K); cls=[cl[i] for i in sub]; n=0; cand=[]; unr=[]
            for r,sup in pool.imap_unordered(work,((cls,s) for s in lazy_jobs(cls)),chunksize=256):
                n+=1
                if r=='UNRESOLVED': unr.append(sup)
                elif r is not None: cand.append(dict(sup=sup,sol=r))
            tot['jobs']+=n; tot['cand']+=len(cand); tot['unres']+=len(unr)
            with gzip.open(CK,'at') as f: f.write(json.dumps(dict(blk=blk,jobs=n,cand=cand,unresolved=unr[:50],n_unres=len(unr)))+'\n')
            print('k',k,'K',ki,K,'sub',sub,'jobs',n,'cand',len(cand),'unres',len(unr),round(time.time()-t0),flush=True)
    print('SUMMARY k',k,json.dumps(tot),'(this invocation)',flush=True)
