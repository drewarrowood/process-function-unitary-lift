"""H.21.1 (Round 14): explicit temporal circuit with time-delocalised subsystems (TDS) for the H.12 Switchboard, built by following
the constructive proof of Wechs-Branciard-Oreshkov (WBO, arXiv:2201.11832, Prop. 1, Suppl. Notes 2-3), checked to machine precision.
(0) Phase form.  In Hadamard frames on P and on the agents' inputs, H.12 is the phase process D: |z>_P|o>_AO -> Phi(o,z)|z>_AI|o>_F,
    Phi = i^{pre(z)} (-1)^{oA (zB or zC)} i^{oB zA zC} (-1)^{oC zB (1-zA)},  pre = 3zC+2zA+zBzC+3zAzC+zAzB+2zAzBzC  (mod 4).
    Each agent's output phase depends on the other two agents' inputs (no self terms) -- the cyclic dependency in closed form.
(1) Fix U_C (qubit + qubit ancilla c').  V*U_C is a bipartite unitary process for A,B with past P16=(P3,c') and future F16=(F3,c').
    Its sector algebra Zalg = {X on P16 : X(x)1 commutes with U^dag L(A_I B_I) U} is computed by linear algebra; a projector in Zalg
    splits P16 = P^{A<B} (+) P^{B<A} (Barrett-Lorenz-Oreshkov / Yokojima et al. decomposition, used by WBO).
(2) In each sector the order is definite; matrix units of the M2 algebra generated by the first party's input give
    nu1: P^sector -> T1 (x) E1, nu2: T1' (x) E1 -> T2 (x) E2, nu3: E2 (x) T2' -> F^sector (|E1|=|E2|=4 in both sectors, so
    WBO's padding qubits p,f are not needed).  Temporal circuit (WBO Fig. 3):
      omega1 = nu1^{A<B} (x)|0>_Q + nu1^{B<A} (x)|1>_Q ;  slot 1: U_A if Q=0 else U_B ;  omega2 = nu2^{A<B} (Q=0) / nu2^{B<A} (Q=1) ;
      slot 2: U_B if Q=0 else U_A ;  omega3 = nu3^{A<B} <0|_Q + nu3^{B<A} <1|_Q.
    Check: circuit == cyclic composition Cyc(V_H12; U_A,U_B,U_C) for Haar-random U_A,U_B,U_C.
(3) TDS for C (WBO Suppl. Note 3B): V = U1 * id^{Z Zbar} * U2 with U1: P A_O B_O -> C_I Z, U2: C_O Zbar -> A_I B_I F (|Z|=16),
    computed from the M2 algebra of C_I.  Check: U2^dag . [omega-chain with A,B wires open] . U1^dag = U_C (x) id_Z, i.e.
    R(U_C)*R' = V*U_C (WBO Eq. (tripartite_final)); with (2) this is the TDS realisation of Prop. 1 (J_in, J_out as WBO Eqs. (42)-(43)).
(4) Facts printed: dim Zalg, centre dim, whether Zalg depends on U_C (the omegas are functions of U_C, as Prop. 1 allows).
(5) Structured circuit (rg_h12.py): V_H12 = (Hd X_C)_AI (Hd X_A)_F L_G^T (Hd)_AO (X_C Pre Hd)_P with G = sqrt(X) and L_G the
    Lugano purification with Bob's flip X replaced by G.  WBO's Baumeler-Wolf circuit (tds_h13.py) with ONE change -- in omega2
    (branch Q=0) the CNOT T1' -> E1 becomes a controlled-G -- realises L_G; its omegas use U_C only through the time-local instances
    U_C (omega1) and U_C sigma_x U_C^dag (omega3).  Reversed and transposed, with frame-rotated agents, it realises H.12."""
